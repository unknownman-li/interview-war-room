/*
 * 从站点题库生成检索索引：node scripts/build-index.cjs
 * 输出 src/search-index.js（Worker 直接 import）
 *
 * 为了控制 Worker CPU：权重在构建期算好，运行时只做关键词集合求交。
 * 修改 assets/data-*.js 后重新执行一次。
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const workerDir = path.resolve(__dirname, '..');
const siteDir = path.resolve(workerDir, '..');
const assetsDir = path.join(siteDir, 'assets');
const outFile = path.join(workerDir, 'src', 'search-index.js');

function decodeEntities(s) {
  return s
    .replace(/&nbsp;/g, ' ')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&');
}

function plain(html) {
  return decodeEntities(String(html || '')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/(p|li|h[1-6]|blockquote|pre|tr)>/gi, '\n')
    .replace(/<[^>]+>/g, ' '))
    .replace(/[ \t]+/g, ' ')
    .replace(/\n{2,}/g, '\n')
    .trim();
}

function clip(s, n) {
  s = String(s || '').replace(/\s+/g, ' ').trim();
  return s.length > n ? s.slice(0, n) + '…' : s;
}

const CJK_RUN = /[\u4e00-\u9fff]+/g;
const LATIN = /[a-z0-9][a-z0-9+#._-]*/g;

function tokenize(s) {
  const text = String(s || '').toLowerCase();
  const out = [];
  const latin = text.match(LATIN);
  if (latin) for (const t of latin) out.push(t);
  const runs = text.match(CJK_RUN);
  if (runs) {
    for (const run of runs) {
      if (run.length === 1) { out.push(run); continue; }
      for (let i = 0; i < run.length - 1; i++) out.push(run.slice(i, i + 2));
    }
  }
  return out;
}

const sandbox = { window: {}, console };
vm.createContext(sandbox);
for (const name of fs.readdirSync(assetsDir)) {
  if (!/^data-\d+\.js$/.test(name)) continue;
  vm.runInContext(fs.readFileSync(path.join(assetsDir, name), 'utf8'), sandbox, { filename: name });
}

const modules = sandbox.window.MODULES || [];
const docs = [];

for (const m of modules) {
  for (let i = 0; i < m.items.length; i++) {
    const it = m.items[i];
    const text = clip(m.title + ' ' + (m.tags || []).join(' ') + ' ' + plain(it.a), 620);
    const qTokens = tokenize(it.q);
    const metaTokens = tokenize(m.title + ' ' + (m.tags || []).join(' '));
    const bodyTokens = tokenize(text);

    const tf = new Map();
    const boost = new Map();
    for (const t of qTokens) { tf.set(t, (tf.get(t) || 0) + 1); boost.set(t, 3); }
    for (const t of metaTokens) { tf.set(t, (tf.get(t) || 0) + 1); boost.set(t, Math.max(boost.get(t) || 1, 2)); }
    for (const t of bodyTokens) tf.set(t, (tf.get(t) || 0) + 1);

    docs.push({ m: m.id, mt: m.title, i: i, q: it.q, s: it.star || 3, t: text, tf: tf, boost: boost });
  }
}

const N = docs.length;
const df = new Map();
for (const d of docs) {
  for (const t of d.tf.keys()) df.set(t, (df.get(t) || 0) + 1);
}

const MAX_KEYWORDS = 48;
for (const d of docs) {
  const scored = [];
  for (const [t, f] of d.tf) {
    const n = df.get(t) || 1;
    if (n > N * 0.35 && !d.boost.has(t)) continue;
    const idf = Math.log(1 + N / n);
    const w = (1 + Math.log(f)) * idf * (d.boost.get(t) || 1);
    scored.push([t, Math.round(w * 100) / 100]);
  }
  scored.sort(function (a, b) { return b[1] - a[1]; });
  d.k = scored.slice(0, MAX_KEYWORDS);
  delete d.tf;
  delete d.boost;
}

const header = '/* AUTO-GENERATED by scripts/build-index.cjs — 不要手改，改题库后重新生成 */\n';
const body = 'export const DOCS = ' + JSON.stringify(docs) + ';\n';
fs.writeFileSync(outFile, header + body, 'utf8');

const kb = (Buffer.byteLength(header + body) / 1024).toFixed(1);
console.log('indexed ' + docs.length + ' questions from ' + modules.length + ' modules -> ' + path.relative(workerDir, outFile) + ' (' + kb + ' KB)');
